package MethodsAndConstructors;

public class Greetings {
	
	// 1) No parameters and No return value
	
	void m1()
	{
		System.out.println("Hello...");
	}
	
	
	//2) No parameters and Return value
	
	String m2()
	{
		return("heloo how are you");
	}

	// 3) Takes parameters and no return value
	
	void m3(String name)
	{
		System.out.println("hello "+name);
	}
	
	
	//4) Takes parameters and Returns value
	
	String m4(String name)
	{
		return("Hello  " +name);
	}

	
	
	
	
	
}
